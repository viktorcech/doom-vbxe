#!/usr/bin/env python3
"""THE RAM budget: what is occupied at runtime, and what is left for new code.

This is the single source of truth for the RUNTIME picture. memory_map.inc owns
the addresses; this file owns the knowledge of which RAM is *destroyed later* and
therefore cannot hold code even though no XEX segment claims it. That distinction
is not visible to MADS: the assembler happily places code at $B000, and the level
loader then streams textures over it -- the symptom is a flat pink screen at boot,
with no error anywhere. It has already cost one debugging session.

  python tools/ram_map.py                    # print the budget
  python tools/ram_map.py --update           # rewrite the block in memory_map.inc
  python tools/check_xex.py <xex>            # fail the build on any overlap

RESERVED is imported by tools/check_xex.py so the two can never drift apart.

HOW TO READ THE MAP WHEN YOU NEED SPACE (2026-08-20, written down after an hour
of looking for 30 bytes and finding them three times where they were not):

  1. "FREE RAM FOR NEW CODE: NONE" below is the truth, and it is a truth about
     a 64 KB machine that is FULL, not about fragmentation. The accounting:
     ~47.4 KB of XEX code+data, ~16.4 KB of RAM that carries no XEX segment but
     is written at RUNTIME (the $4000 map slot, the $C000 things slot, the
     $1000 SIO staging, the $9000 VBXE MEMAC-A window, the under-ROM blob
     landing zones -- that is what RESERVED lists), and the 2 KB hardware hole
     at $D000-$D7FF. There is nothing behind the XEX to discover.

  2. DO NOT trust a gap between XEX segments (tools/tests/_probe_holes.py).
     Equated variables carry no segment, so a "20 byte hole" at $E6C3 is
     MV_SPD, the mover speed array, and code parked there is overwritten by the
     first lift that moves. RESERVED exists precisely because MADS cannot see
     this, and RESERVED does not list every variable -- cross-check the .lab.

  3. DO NOT trust a block's declared _END either. ~150 of the _BASE/_END pairs
     in memory_map.inc OVERLAP another pair: the big blocks were subdivided
     over time and the outer _END was left as a stale upper bound. APREF_END
     ($81FF) is the clearest case -- arena_prefetch really ends at $80F4 and
     MTXPEG/PAINROW/SWFIRE own everything above it, so that block's `ert` guard
     would not fire until the proc had already eaten mtx_pegf. A block's REAL
     slack is (the next _BASE above it) minus (where its code actually ends in
     build/doom_bsp.lst), never _END minus that.

  4. So the only way to add code is the one the budget says: EVICT. Move a cold
     proc to a Rapidus bank or under the ROM, or -- cheaper and what the
     cacodemon's A_HeadAttack did on 2026-08-20 -- change the DATA LAYOUT so
     the new thing needs no new bytes at all (there, renumbering mk_atk so the
     four missile actions stayed contiguous kept at_tables.inc four rows wide
     and paid for the feature out of two bytes saved in ai_fire's dispatch).
"""
