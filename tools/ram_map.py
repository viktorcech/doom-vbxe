# Reserves: real RAM we could take back, and what it costs.
# (The old "under-ROM RAM unused" lines are gone: $C000-$CBFF is the streamed
#  THINGS blob and $D800-$F7FF the streamed map HIGH region -- see RESERVED.)
RECLAIMABLE = []


def segments(path=XEX):
    """Parse a segmented Atari XEX -> [(start, end)]."""
    d = open(path, 'rb').read()
    out, i = [], 2
    while i + 4 <= len(d):
        s, e = struct.unpack('<HH', d[i:i + 4])
        i += 4
        if s == 0xFFFF:                      # extra $FFFF header, skip
            continue
        out.append((s, e))
        i += e - s + 1
    return sorted(out)


def free_blocks(segs):
    used = sorted([(s, e) for s, e in segs] +
                  [(s, e) for s, e, _ in RESERVED + OS_LOW])
    free, cur = [], 0x0000
    for s, e in used:
        if s > cur:
            free.append((cur, s - 1))
        cur = max(cur, e + 1)
    if cur <= 0xFFFF:
        free.append((cur, 0xFFFF))
    return [(a, b) for a, b in free if b - a + 1 >= 32]


def render(segs):
    free = free_blocks(segs)
    total = sum(b - a + 1 for a, b in free)
    L = []
    A = L.append
    A(BEGIN)
    A(';')
    if free:
        biggest = max((b - a + 1, a, b) for a, b in free)
        A(';   FREE RAM FOR NEW CODE:  %d B total, biggest contiguous block %d B ($%04X-$%04X)'
          % (total, biggest[0], biggest[1], biggest[2]))
    else:
        # 2026-08-08: this used to be `max()` over an empty list, so the day the
        # map filled up the BUILD died with a ValueError instead of telling
        # anyone why. There is no block of >= 32 B left anywhere in the 64 KB.
        A(';   FREE RAM FOR NEW CODE:  NONE -- not one block of 32 B is left.')
        A(';   The next .proc has to EVICT something: move a cold one to bank $01')
        A(';   or under the ROM, or shrink a table. See the RESERVES below.')
    A(';')
    A(';   A procedure has to fit in ONE block, but it does not matter which: the')
    A(';   port already relocates code with `org` + absolute jsr (collision @ $0900,')
    A(';   check_bbox @ $1B00, tw_setup @ $8D00). When a segment outgrows its hole,')
    A(';   move a whole .proc out rather than letting the segment creep.')
    A(';')
    for a, b in free:
        n = b - a + 1
        note = ''
        if 0x2000 <= a < 0x4000:
            note = 'tail of the $2000 engine segment'
        elif 0x4000 <= a < 0x8600:
            note = 'the seg table left this (probably FAST below $8000)'
        elif 0x8600 <= a < 0x9000:
            note = 'below the MEMAC window'
        elif a >= 0xA000:
            note = 'MUST stay below $B000 (sprites.asm)'
        A(';     $%04X-$%04X  %5d B%s' % (a, b, n, '   ' + note if note else ''))
    A(';')
    A(';   RESERVES -- real RAM, but it costs something to take:')
    for a, b, why in RECLAIMABLE:
        A(';     $%04X-$%04X  %5d B   %s' % (a, b, b - a + 1, why))
    A(';')
    A(';   THE TRAP: MADS does NOT check any of this. Code assembled into RAM that')
    A(';   is overwritten later (the $1000-$13FF SIO staging TEX_STAGE, the $4000')
    A(';   map slot, the streamed under-ROM blobs) assembles clean and then dies')
    A(';   at boot with no message -- a flat pink screen. Guards:')
    A(';     * tools/check_xex.py fails the build on any overlap (build*.ps1)')
    A(';     * the RESERVED list in tools/ram_map.py -- keep it in step with the')
    A(';       loaders (diskio.asm), it is what check_xex enforces')
    A(';     * this block is regenerated by tools/ram_map.py on every build')
    A(END)
    return '\n'.join(L)


# EVERY hand-written asm/inc source carries the banner; ram_map keeps the figure
# in all of them honest. map_syms.inc / atr_layout.inc are generated, so their
# generators (tools/pack_map.py, tools/make_atr_doom.py) emit it themselves.
ASM_FILES = ['bsp_main.asm', 'renderer.asm', 'math.asm', 'collision.asm',
             'doors.asm', 'checkbbox.asm', 'vcache.asm', 'boot.asm',
             'viewsize.asm', 'read_keys.asm',
             'qs_tables.inc', 'recip.inc', 'trig.inc', 'vbxe_regs.inc',
             'atr_layout.inc', 'map_syms.inc']


def refresh_banners(total, biggest):
    """Keep the one-line figure in every .asm banner honest -- a stale number in
    eight files is worse than no number at all."""
    import re
    n = 0
    for f in ASM_FILES:
        path = os.path.join(ROOT, f)
        if not os.path.exists(path):
            continue
        s = open(path, encoding='utf-8', errors='replace').read()
        new = re.sub(r'; RAM BUDGET: \d+ B free, biggest contiguous block \d+ B\.',
                     '; RAM BUDGET: %d B free, biggest contiguous block %d B.' % (total, biggest),
                     s)
        if new != s:
            open(path, 'w', encoding='utf-8').write(new)
            n += 1
    return n


def main():
    if not os.path.exists(XEX):
        sys.exit('ram_map: %s not found -- build first' % XEX)
    block = render(segments())
    if '--update' in sys.argv:
        s = open(INC, encoding='utf-8').read()
        if BEGIN in s and END in s:
            i, j = s.index(BEGIN), s.index(END) + len(END)
            s = s[:i] + block + s[j:]
        else:
            anchor = ';==============================================================\n; 6502 RAM MAP (64 KB)'
            s = s.replace(anchor, block + '\n\n' + anchor, 1)
        open(INC, 'w', encoding='utf-8').write(s)
        free = free_blocks(segments())
        total = sum(b - a + 1 for a, b in free)
        biggest = max((b - a + 1 for a, b in free), default=0)
        n = refresh_banners(total, biggest)
